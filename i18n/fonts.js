// Copies the Google Fonts that bounty.html and vision.html use onto the site,
// so visitors' browsers never contact Google.
//
//   node fonts.js    writes ../assets/fonts/*.woff2 and ../assets/css/fonts-<page>.css
//
// Run it again only if a page's font choice changes (update FONTS below).

const fs = require('fs');
const path = require('path');

const FONTS = {
  bounty: 'https://fonts.googleapis.com/css2?family=Rye&family=Playfair+Display:ital,wght@0,400;0,700;1,400&family=Crimson+Text:ital,wght@0,400;0,600;1,400&display=swap',
  vision: 'https://fonts.googleapis.com/css2?family=Playfair+Display:wght@700;900&family=DM+Sans:wght@300;400;500;600&display=swap',
};

// Google sends woff2 files (the smallest format) only to browsers it knows.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const ROOT = path.join(__dirname, '..');
const fontDir = path.join(ROOT, 'assets', 'fonts');
fs.mkdirSync(fontDir, { recursive: true });

(async () => {
  for (const [page, url] of Object.entries(FONTS)) {
    let css = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();
    const files = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g)].map(m => m[1]))];
    for (const file of files) {
      // e.g. .../s/playfairdisplay/v37/abc.woff2 → playfairdisplay-v37-abc.woff2
      const name = file.replace('https://fonts.gstatic.com/s/', '').replace(/\//g, '-');
      const target = path.join(fontDir, name);
      if (!fs.existsSync(target)) {
        const res = await fetch(file);
        if (!res.ok) throw new Error(`${res.status} for ${file}`);
        fs.writeFileSync(target, Buffer.from(await res.arrayBuffer()));
      }
      css = css.split(file).join(`/assets/fonts/${name}`);
    }
    fs.writeFileSync(path.join(ROOT, 'assets', 'css', `fonts-${page}.css`),
      `/* Self-hosted copy of ${url} — generated by i18n/fonts.js (SIL Open Font Licence) */\n${css}`);
    console.log(`${page}: ${files.length} font files`);
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
