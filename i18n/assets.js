// Builds the site's own copies of the tools that used to load from other
// servers (cdn.tailwindcss.com, cdn.jsdelivr.net, cdnjs.cloudflare.com), so
// voteboxapp.org loads nothing from third parties.
//
//   node assets.js    writes ../assets/css/tailwind.css, ../assets/js/icons.js
//                     and ../assets/js/chart.umd.js
//
// Run it after adding Tailwind classes or Lucide icons to index.html.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const out = (...p) => path.join(ROOT, 'assets', ...p);
fs.mkdirSync(out('css'), { recursive: true });
fs.mkdirSync(out('js'), { recursive: true });

// 1. Tailwind: only the classes index.html uses, same version as the CDN had.
execFileSync(process.execPath, [
  require.resolve('tailwindcss/lib/cli.js'),
  '-c', path.join(__dirname, 'tailwind.config.js'),
  '-i', path.join(__dirname, 'tailwind.input.css'),
  '-o', out('css', 'tailwind.css'),
  '--minify',
], { stdio: 'inherit' });

// 2. Icons: just the Lucide icons index.html uses, from the plain SVG files
// of lucide-static. Keeps the page's existing lucide.createIcons() call.
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const names = [...new Set([...html.matchAll(/data-lucide="([a-z0-9-]+)"/g)].map(m => m[1]))].sort();
const icons = {};
for (const name of names) {
  const svg = fs.readFileSync(path.join(__dirname, 'node_modules', 'lucide-static', 'icons', `${name}.svg`), 'utf8');
  icons[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(out('js', 'icons.js'), `// Generated by i18n/assets.js from lucide-static ${require('lucide-static/package.json').version} (ISC licence).
// Replaces each <i data-lucide="name"> with its SVG icon, like lucide.createIcons().
(function () {
  var ICONS = ${JSON.stringify(icons)};
  var NS = 'http://www.w3.org/2000/svg';
  var DEFAULTS = { xmlns: NS, width: '24', height: '24', viewBox: '0 0 24 24', fill: 'none',
    stroke: 'currentColor', 'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  function createIcons() {
    document.querySelectorAll('i[data-lucide]').forEach(function (el) {
      var name = el.getAttribute('data-lucide');
      if (!ICONS[name]) return;
      var holder = document.createElement('div');
      holder.innerHTML = '<svg xmlns="' + NS + '">' + ICONS[name] + '</svg>';
      var svg = holder.firstChild;
      Object.keys(DEFAULTS).forEach(function (k) { svg.setAttribute(k, DEFAULTS[k]); });
      Array.prototype.forEach.call(el.attributes, function (a) { if (a.name !== 'class') svg.setAttribute(a.name, a.value); });
      svg.setAttribute('class', ['lucide', 'lucide-' + name, el.getAttribute('class') || ''].join(' ').trim());
      el.parentNode.replaceChild(svg, el);
    });
  }
  window.lucide = { createIcons: createIcons };
})();
`);

// 3. Chart.js for how-its-funded.html, same version the page used.
fs.copyFileSync(path.join(__dirname, 'node_modules', 'chart.js', 'dist', 'chart.umd.js'), out('js', 'chart.umd.js'));

console.log(`tailwind.css ${fs.statSync(out('css', 'tailwind.css')).size} B · icons.js ${names.length} icons, ${fs.statSync(out('js', 'icons.js')).size} B · chart.umd.js ${fs.statSync(out('js', 'chart.umd.js')).size} B`);
